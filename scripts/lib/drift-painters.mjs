/**
 * The painters the drift deals from, and nothing about how they are dealt.
 *
 * This list is a curatorial decision, not a measurement, and it is kept in its
 * own file so that it reads as one. The drift used to deal from a spread of the
 * whole archive, which is a defensible sample and a bad deck: a reader met
 * ground plans, engraved title pages, plates from pattern books and photographs
 * of church façades, and was asked whether they were pulled. Most of those
 * cards are unanswerable. You cannot be drawn towards or pushed off a building
 * survey you have no way to read, and forty of them measure patience rather
 * than eye.
 *
 * So the deck is now paintings by painters a reader has a chance of having met
 * — in a museum, on a book cover, in a schoolroom. "Famous" is doing real work
 * here and it is worth being honest about whose famous: this is a German
 * art-historical teaching archive, so the canon it holds is the European one
 * with a German centre of gravity, and the list below reproduces that rather
 * than correcting it. There is no Hokusai in it, no Hiroshige, no Kunisada,
 * though the archive holds hundreds of their sheets and they are as famous as
 * anyone here — they made prints, and the deck is paintings. The same rule
 * costs Dürer and Rembrandt most of their output and Daumier nearly all of it.
 *
 * Names are the archive's own spellings, matched exactly, because the archive
 * spells its people the way its cataloguers did — "Raffaelo Santi", "Francisco
 * José Goya Lucientes", "Francesco de' Guardi" — and a fuzzy match on a surname
 * quietly collects the wrong Cranach. Where the archive holds one painter under
 * several spellings, every spelling is listed; where it holds a workshop or a
 * copy as a separate artist ("Cranach-Werkstatt", "Leonardo da Vinci
 * (Werkstatt)"), it is left out, because a card that says Leonardo under a
 * workshop panel is a card that lies.
 *
 * Membership here makes a work *eligible*, never selected. Whether an eligible
 * work is a painting at all is decided per work by
 * `scripts/pick-drift-paintings.mjs`, which is where Dürer's 371 records become
 * the handful that are panels.
 */

